import { expect, test } from '@playwright/test';
import { DEMO_DOC_KEY, homeHeading, openDevice, PHONE_DOC, resetServer, SETUP_CODE, welcome } from '../helpers';
test('stratis signs up after bringing the home online', async ({ browser, baseURL, request }) => {
  await resetServer(request);
  const s = await openDevice(browser, baseURL!, { localStorage: { [DEMO_DOC_KEY]: JSON.stringify(PHONE_DOC) }, path: `/?setup=${SETUP_CODE}` });
  await s.page.getByRole('button', { name: 'Bring It Online' }).click();
  await s.page.getByRole('button', { name: 'Continue' }).click();
  await expect(homeHeading(s.page)).toBeVisible();
  const n = await openDevice(browser, baseURL!);
  n.page.on('response', async (r) => { if (r.url().includes('/api/home') && r.request().method() === 'POST') console.log('POST', r.status(), (await r.text()).slice(0, 300)); });
  const door = welcome(n.page);
  await door.getByLabel('Your name').fill('Stratis');
  await door.getByLabel('Email').fill('stratisvx@example.com');
  await door.getByLabel('Password').fill('averylongpass');
  await door.getByRole('button', { name: 'Create Account' }).click();
  await n.page.waitForTimeout(3000);
  console.log('alert:', await door.getByRole('alert').count() ? await door.getByRole('alert').innerText() : 'none');
  console.log('home visible:', await homeHeading(n.page).isVisible());
  console.log('errors:', n.errors);
});
