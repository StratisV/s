import type { BreathPattern, Meditation } from '../types';

/**
 * The guided meditations. Together ones are for a parent and child side by side, written to be
 * read aloud to the child with the parent joining in; solo ones are for the parent alone. Each
 * step's seconds add up to the session's length, and a breathing step lasts a whole number of
 * breaths so the circle always finishes on an out-breath.
 *
 * Where the thinking comes from:
 * - Mindfulness for children: MindUP (Schonert-Reichl et al., 2015, Developmental Psychology),
 *   the Mindfulness in Schools Project's .b and Paws b curricula, and the weather report of
 *   feelings from Eline Snel's "Sitting Still Like a Frog".
 * - Paced breathing with a longer out-breath, which slows the heart and calms the body
 *   (Zaccaro et al., 2018, Frontiers in Human Neuroscience; Balban et al., 2023, Cell Reports Medicine).
 * - Naming a feeling to soften it, "affect labelling" (Lieberman et al., 2007, Psychological Science).
 * - Progressive muscle relaxation for young children, the "squeeze the lemon" script
 *   (Koeppen, 1974, Elementary School Guidance and Counseling).
 * - Mindful parenting (Duncan, Coatsworth and Greenberg, 2009) and rupture and repair (Tronick).
 * - The self-compassion break (Kristin Neff), loving kindness, and the three-step breathing
 *   space from mindfulness-based cognitive therapy (Segal, Williams and Teasdale).
 *
 * Gentle and trauma-sensitive throughout: every instruction is an invitation, eyes can stay
 * open, holds can be skipped, and it is always fine to stop.
 */

/** Little ones (about 2 to 8): in for 3, out for 4. */
const SMALL: BreathPattern = { inhale: 3, exhale: 4 };
/** Older children, teens and grown-ups: in for 4, out for 6 (about six breaths a minute). */
const SLOW: BreathPattern = { inhale: 4, exhale: 6 };
/** Square breathing for the middle years: three on each side. */
const SQUARE: BreathPattern = { inhale: 3, hold: 3, exhale: 3, rest: 3 };
/** Box breathing for teens: four on each side. */
const BOX: BreathPattern = { inhale: 4, hold: 4, exhale: 4, rest: 4 };

